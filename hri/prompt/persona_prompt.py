def get_persona_prompt(persona: str) -> list[dict]:
    """페르소나의 system 메시지와 few-shot 3쌍으로 messages 앞부분을 만든다.
 
    system 내용: PERSONAS(말투·용어 난이도) + ANSWER_FORMATS(질의응답 답변 구조)
    반환 순서: [system, user, assistant, user, assistant, user, assistant]
    PERSONAS에 없는 페르소나면 '실무자'를 사용한다.
    """
    if persona not in PERSONAS:
        persona = "실무자"
 
    messages = [{"role": "system", "content": f"{PERSONAS[persona]} {ANSWER_FORMATS[persona]}"}]
    for example in FEW_SHOT_EXAMPLES[persona]:
        messages.append({"role": "user", "content": example["question"]})
        messages.append({"role": "assistant", "content": example["answer"]})
    return messages

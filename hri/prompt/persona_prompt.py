def get_persona_prompt(persona: str) -> list[dict]:
    """페르소나의 system 메시지와 few-shot 쌍으로 messages 앞부분을 만든다.

    반환 순서: [system, user, assistant, user, assistant]
    PERSONAS에 없는 페르소나면 '실무자'를 사용한다.
    """
    if persona not in PERSONAS:
        persona = "실무자"

    messages = [{"role": "system", "content": PERSONAS[persona]}]
    for example in FEW_SHOT_EXAMPLES[persona]:
        messages.append({"role": "user", "content": example["question"]})
        messages.append({"role": "assistant", "content": example["answer"]})
    return messages
